-- =====================================================================
-- Nyne Hotels CRM – database schema (PostgreSQL 14+ / Supabase)
-- Run this first, then seed.sql.
--
-- Conventions
-- * Lists of allowed values use CHECK constraints (not ENUM types) so new
--   values can be added later with a simple ALTER TABLE.
-- * Every table has the same six audit columns:
--     created_at, created_by, updated_at, updated_by, deleted_at, deleted_by
--   except contact_tags (a link) and contact_merges (a permanent log),
--   which are never edited and only have created_at / created_by.
-- * The *_by columns are filled automatically from the logged-in staff
--   member. The app runs  SET LOCAL app.staff_id = '<staff id>'  at the
--   start of each request; nobody has to remember to fill them in.
--   NULL in a *_by column means the system did it (e.g. the initial import).
-- * Deleting = setting deleted_at (soft delete). The row stays for history,
--   and every view hides it. Uniqueness rules only apply to rows that are
--   not deleted, so a deleted email or tag can be added again.
-- =====================================================================

BEGIN;

-- ---------- who is making this change? ----------
CREATE OR REPLACE FUNCTION current_staff_id() RETURNS bigint AS $$
  SELECT nullif(current_setting('app.staff_id', true), '')::bigint
$$ LANGUAGE sql STABLE;

-- ---------- audit trigger for normal tables ----------
-- INSERT: stamps created_* and updated_*.
-- UPDATE: created_* can never change; updated_* is always refreshed;
--         deleted_by is stamped when a row is deleted and cleared when restored.
CREATE OR REPLACE FUNCTION set_audit_columns() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.created_at := coalesce(NEW.created_at, now());
    NEW.created_by := coalesce(current_staff_id(), NEW.created_by);
    NEW.updated_at := NEW.created_at;
    NEW.updated_by := NEW.created_by;
    IF NEW.deleted_at IS NOT NULL THEN
      NEW.deleted_by := coalesce(current_staff_id(), NEW.deleted_by);
    END IF;
  ELSE
    NEW.created_at := OLD.created_at;
    NEW.created_by := OLD.created_by;
    NEW.updated_at := now();
    NEW.updated_by := coalesce(current_staff_id(),
                               CASE WHEN NEW.updated_by IS DISTINCT FROM OLD.updated_by THEN NEW.updated_by END);
    IF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
      NEW.deleted_by := coalesce(current_staff_id(), NEW.deleted_by);
    ELSIF NEW.deleted_at IS NULL THEN
      NEW.deleted_by := NULL;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------- audit trigger for the two insert-only tables ----------
CREATE OR REPLACE FUNCTION set_created_columns() RETURNS trigger AS $$
BEGIN
  NEW.created_at := coalesce(NEW.created_at, now());
  NEW.created_by := coalesce(current_staff_id(), NEW.created_by);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =====================================================================
-- 1. STAFF USERS – who uses the CRM (created first: every table points here)
-- =====================================================================
CREATE TABLE staff_users (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name   text NOT NULL,
  last_name    text,
  email        text,                                   -- optional; staff sign in with a username
  role         text NOT NULL CHECK (role IN ('admin','management','marketing')),
  property_id  text,                                   -- home hotel; NULL = group-wide (FK added below)
  is_active    boolean NOT NULL DEFAULT true,
  -- the Better Auth sign-in account (auth_users: username, password, sessions).
  -- The auth_* tables and this FK are created by drizzle/0002_auth_and_settings.sql.
  auth_user_id text UNIQUE,
  created_at   timestamptz NOT NULL DEFAULT now(),
  created_by   bigint REFERENCES staff_users(id),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  updated_by   bigint REFERENCES staff_users(id),
  deleted_at   timestamptz,
  deleted_by   bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX staff_users_email_uq ON staff_users (lower(email)) WHERE deleted_at IS NULL;

-- =====================================================================
-- 2. PROPERTIES – the hotels
-- =====================================================================
CREATE TABLE properties (
  id             text PRIMARY KEY,                     -- 'P01' … 'P08'
  name           text NOT NULL,
  location       text,
  property_type  text,
  web_url        text,
  is_active      boolean NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  created_by     bigint REFERENCES staff_users(id),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  updated_by     bigint REFERENCES staff_users(id),
  deleted_at     timestamptz,
  deleted_by     bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX properties_name_uq ON properties (name) WHERE deleted_at IS NULL;
ALTER TABLE staff_users ADD FOREIGN KEY (property_id) REFERENCES properties(id);

-- =====================================================================
-- 3. EMPLOYEES – everyone who works at the hotels (chefs, drivers, butlers …)
--     Most never log into the CRM; staff_user_id links the ones who do.
-- =====================================================================
CREATE TABLE employees (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name     text NOT NULL,
  last_name      text,
  property_id    text REFERENCES properties(id),       -- NULL = works across the group
  department     text NOT NULL DEFAULT 'other'
                 CHECK (department IN ('front_office','housekeeping','food_beverage','kitchen','spa',
                                       'transport','activities','maintenance','management','other')),
  job_title      text,                                 -- e.g. 'Butler', 'Head Chef', 'Driver'
  staff_user_id  bigint REFERENCES staff_users(id),    -- set if this employee also uses the CRM
  is_active      boolean NOT NULL DEFAULT true,        -- false once they leave; their feedback stays
  created_at    timestamptz NOT NULL DEFAULT now(),
  created_by    bigint REFERENCES staff_users(id),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  updated_by    bigint REFERENCES staff_users(id),
  deleted_at    timestamptz,
  deleted_by    bigint REFERENCES staff_users(id)
);
CREATE INDEX employees_property_idx ON employees (property_id, department) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX employees_staff_user_uq ON employees (staff_user_id)
  WHERE staff_user_id IS NOT NULL AND deleted_at IS NULL;

-- =====================================================================
-- 4. COUNTRIES – fixed list (ISO 3166) so nobody types "Austrailia"
-- =====================================================================
CREATE TABLE countries (
  code        char(2) PRIMARY KEY,                     -- ISO code: 'LK', 'GB', 'IN' …
  name        text NOT NULL,
  dial_code   text,                                    -- '+94' – helps match a phone number to a country
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  bigint REFERENCES staff_users(id),
  deleted_at  timestamptz,
  deleted_by  bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX countries_name_uq ON countries (name) WHERE deleted_at IS NULL;

-- =====================================================================
-- 5. OCCASIONS – pick-list for why someone is staying or asking about a stay
-- (special_dates has its own fixed list: birthday, anniversary …)
-- =====================================================================
CREATE TABLE occasions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  sort_order  smallint NOT NULL DEFAULT 100,           -- order shown in the drop-down
  is_active   boolean NOT NULL DEFAULT true,           -- false = retired, hidden from drop-downs
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  bigint REFERENCES staff_users(id),
  deleted_at  timestamptz,
  deleted_by  bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX occasions_name_uq ON occasions (lower(name)) WHERE deleted_at IS NULL;

-- =====================================================================
-- 6. COMPANIES – travel agents, DMCs, OTAs, corporates
-- =====================================================================
CREATE TABLE companies (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              text NOT NULL,
  company_type      text NOT NULL DEFAULT 'travel_agent'
                    CHECK (company_type IN ('travel_agent','inbound_dmc','outbound_agent',
                                            'ota','corporate','media','other')),
  country_code      char(2) REFERENCES countries(code),
  address           text,
  website           text,
  commission_notes  text,
  account_owner_id  bigint REFERENCES staff_users(id),
  status            text NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active','prospect','dormant')),
  created_at        timestamptz NOT NULL DEFAULT now(),
  created_by        bigint REFERENCES staff_users(id),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  updated_by        bigint REFERENCES staff_users(id),
  deleted_at        timestamptz,
  deleted_by        bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX companies_name_uq ON companies (lower(name)) WHERE deleted_at IS NULL;

-- =====================================================================
-- 7. CONTACTS – one row per person (guests, leads, agent contacts, influencers)
-- =====================================================================
CREATE TABLE contacts (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name       text,
  last_name        text,                               -- everything after the first word, e.g. 'De Silva'
  contact_type     text NOT NULL
                   CHECK (contact_type IN ('guest','lead','agent_contact','influencer')),
  lifecycle_stage  text NOT NULL DEFAULT 'lead'
                   CHECK (lifecycle_stage IN ('lead','enquired','booked','stayed','repeat_guest',
                                              'stayed_hotel_unknown','agent_contact','influencer')),
  market           text NOT NULL DEFAULT 'unknown'
                   CHECK (market IN ('local','foreign','unknown')),
  country_code     char(2) REFERENCES countries(code),
  company_id       bigint REFERENCES companies(id) ON DELETE SET NULL,
  designation      text,
  vip_reason       text,                               -- why they are VIP / industry
  status           text NOT NULL DEFAULT 'active'
                   CHECK (status IN ('active','do_not_contact')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  created_by       bigint REFERENCES staff_users(id),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  updated_by       bigint REFERENCES staff_users(id),
  deleted_at       timestamptz,
  deleted_by       bigint REFERENCES staff_users(id)
);
CREATE INDEX contacts_stage_idx   ON contacts (lifecycle_stage) WHERE deleted_at IS NULL;
CREATE INDEX contacts_market_idx  ON contacts (market, country_code) WHERE deleted_at IS NULL;
CREATE INDEX contacts_name_idx    ON contacts (lower(last_name), lower(first_name));
CREATE INDEX contacts_company_idx ON contacts (company_id);

-- =====================================================================
-- 8. CONTACT METHODS – emails and phones (several per person)
-- =====================================================================
CREATE TABLE contact_methods (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id   bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  kind         text NOT NULL CHECK (kind IN ('email','phone')),
  value        text NOT NULL,
  is_primary   boolean NOT NULL DEFAULT false,
  is_shared    boolean NOT NULL DEFAULT false,         -- agent/office/family address: never market, never match on
  is_whatsapp  boolean,                                -- NULL = not yet known
  status       text NOT NULL DEFAULT 'unverified'
               CHECK (status IN ('valid','unverified','bounced','invalid')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  created_by   bigint REFERENCES staff_users(id),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  updated_by   bigint REFERENCES staff_users(id),
  deleted_at   timestamptz,
  deleted_by   bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX contact_methods_uq ON contact_methods (contact_id, kind, value) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX contact_methods_one_primary ON contact_methods (contact_id, kind)
  WHERE is_primary AND deleted_at IS NULL;
CREATE INDEX contact_methods_value_idx ON contact_methods (lower(value));   -- duplicate check on new imports

-- =====================================================================
-- 9. SPECIAL DATES – birthdays, anniversaries and other occasions
--    Stored as month + day (+ optional year) because guests often share
--    the date but not the year, and so "coming up next month" is easy.
-- =====================================================================
CREATE TABLE special_dates (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id  bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  occasion    text NOT NULL CHECK (occasion IN ('birthday','wedding_anniversary','partner_birthday',
                                                'child_birthday','other')),
  label       text,                                    -- e.g. partner's or child's name, or what "other" is
  month       smallint NOT NULL CHECK (month BETWEEN 1 AND 12),
  day         smallint NOT NULL CHECK (day BETWEEN 1 AND 31),
  year        smallint CHECK (year BETWEEN 1900 AND 2100),   -- blank if unknown
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  bigint REFERENCES staff_users(id),
  deleted_at  timestamptz,
  deleted_by  bigint REFERENCES staff_users(id),
  -- rejects impossible dates such as 31 April (2000 is a leap year, so 29 Feb is allowed)
  CHECK (make_date(coalesce(year, 2000), month, day) IS NOT NULL)
);
CREATE INDEX special_dates_contact_idx ON special_dates (contact_id);
CREATE INDEX special_dates_md_idx      ON special_dates (month, day) WHERE deleted_at IS NULL;

-- =====================================================================
-- 10. STAYS – one row per visit
-- =====================================================================
CREATE TABLE stays (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id          bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  property_id         text NOT NULL REFERENCES properties(id),
  arrival_date        date,
  departure_date      date,
  nights              integer GENERATED ALWAYS AS (departure_date - arrival_date) STORED,
  booking_reference   text,                            -- reference from the booking system; one per hotel
  room_type           text,                            -- as given by the booking system
  adults              smallint,
  children            smallint,
  room_revenue        numeric(12,2),
  currency            char(3),
  channel             text NOT NULL DEFAULT 'unknown'
                      CHECK (channel IN ('direct','travel_agent','ota','owner_guest','website',
                                         'walk_in','online_unclear','mixed','unknown')),
  booking_company_id  bigint REFERENCES companies(id), -- agent or OTA that made the booking
  occasion_id         bigint REFERENCES occasions(id),
  created_at          timestamptz NOT NULL DEFAULT now(),
  created_by          bigint REFERENCES staff_users(id),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  updated_by          bigint REFERENCES staff_users(id),
  deleted_at          timestamptz,
  deleted_by          bigint REFERENCES staff_users(id),
  CHECK (departure_date IS NULL OR arrival_date IS NULL OR departure_date >= arrival_date)
);
CREATE INDEX stays_contact_idx  ON stays (contact_id);
CREATE INDEX stays_property_idx ON stays (property_id, arrival_date) WHERE deleted_at IS NULL;
-- the same booking can never be loaded twice
CREATE UNIQUE INDEX stays_booking_ref_uq ON stays (property_id, booking_reference)
  WHERE booking_reference IS NOT NULL AND deleted_at IS NULL;

-- =====================================================================
-- 11. FEEDBACK – the guest's answer to the post-stay feedback form
--     One per stay. The guest and hotel come from the stay.
-- =====================================================================
CREATE TABLE feedback (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stay_id       bigint NOT NULL REFERENCES stays(id) ON DELETE CASCADE,
  rating        smallint CHECK (rating BETWEEN 1 AND 5),   -- 1 = poor … 5 = excellent
  review        text,                                      -- the guest's written comments
  submitted_at  timestamptz NOT NULL DEFAULT now(),        -- when the guest sent the form
  created_at    timestamptz NOT NULL DEFAULT now(),
  created_by    bigint REFERENCES staff_users(id),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  updated_by    bigint REFERENCES staff_users(id),
  deleted_at    timestamptz,
  deleted_by    bigint REFERENCES staff_users(id),
  CHECK (rating IS NOT NULL OR nullif(trim(review), '') IS NOT NULL)   -- an empty form is not feedback
);
CREATE UNIQUE INDEX feedback_one_per_stay ON feedback (stay_id) WHERE deleted_at IS NULL;
CREATE INDEX feedback_submitted_idx ON feedback (submitted_at DESC) WHERE deleted_at IS NULL;

-- =====================================================================
-- 12. EMPLOYEE MENTIONS – a guest praising or criticising a specific employee
--     in their feedback. One row per employee mentioned. If staff can't tell
--     who the guest meant, keep the name as written and link the employee later.
-- =====================================================================
CREATE TABLE employee_mentions (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feedback_id      bigint NOT NULL REFERENCES feedback(id) ON DELETE CASCADE,
  employee_id      bigint REFERENCES employees(id),
  name_as_written  text,                               -- what the guest wrote, e.g. 'Kamal the driver'
  sentiment        text NOT NULL CHECK (sentiment IN ('positive','negative')),
  comment          text,                               -- what the guest said about them
  created_at    timestamptz NOT NULL DEFAULT now(),
  created_by    bigint REFERENCES staff_users(id),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  updated_by    bigint REFERENCES staff_users(id),
  deleted_at    timestamptz,
  deleted_by    bigint REFERENCES staff_users(id),
  CHECK (employee_id IS NOT NULL OR nullif(trim(name_as_written), '') IS NOT NULL)
);
CREATE INDEX employee_mentions_employee_idx ON employee_mentions (employee_id) WHERE deleted_at IS NULL;
CREATE INDEX employee_mentions_feedback_idx ON employee_mentions (feedback_id);
CREATE UNIQUE INDEX employee_mentions_once ON employee_mentions (feedback_id, employee_id)
  WHERE employee_id IS NOT NULL AND deleted_at IS NULL;

-- =====================================================================
-- 13. PREFERENCES – likes and dislikes  (created_by = who noted it; other remarks go in notes)
-- =====================================================================
CREATE TABLE preferences (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id  bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  kind        text NOT NULL CHECK (kind IN ('like','dislike')),
  category    text CHECK (category IN ('food_drink','dietary_health','room','activity',
                                       'occasion','background','other')),
  body        text NOT NULL,
  stay_id     bigint REFERENCES stays(id) ON DELETE SET NULL,   -- the stay also tells you the hotel
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  bigint REFERENCES staff_users(id),
  deleted_at  timestamptz,
  deleted_by  bigint REFERENCES staff_users(id)
);
CREATE INDEX preferences_contact_idx ON preferences (contact_id);

-- =====================================================================
-- 14. CONSENTS – marketing permission per person per channel
-- =====================================================================
CREATE TABLE consents (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id  bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  channel     text NOT NULL CHECK (channel IN ('email','whatsapp')),
  status      text NOT NULL DEFAULT 'unknown'
              CHECK (status IN ('opted_in','opted_out','not_opted_in','unknown')),
  source      text,                                    -- where permission was given: 'wix', 'check_in_form' …
  evidence    text,                                    -- wording shown / original value
  given_at    timestamptz,                             -- when the person gave or withdrew permission
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  bigint REFERENCES staff_users(id),
  deleted_at  timestamptz,
  deleted_by  bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX consents_uq ON consents (contact_id, channel) WHERE deleted_at IS NULL;

-- =====================================================================
-- 15. TAGS – flexible labels (VIP, friends & family, …)
-- =====================================================================
CREATE TABLE tags (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  bigint REFERENCES staff_users(id),
  deleted_at  timestamptz,
  deleted_by  bigint REFERENCES staff_users(id)
);
CREATE UNIQUE INDEX tags_name_uq ON tags (lower(name)) WHERE deleted_at IS NULL;

-- A link between a person and a tag. Removing a tag deletes the link,
-- so this table only records who added it and when.
CREATE TABLE contact_tags (
  contact_id  bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  tag_id      bigint NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  PRIMARY KEY (contact_id, tag_id)
);

-- =====================================================================
-- 16. LEADS – each time someone shows interest, from first message to booked or lost (empty at launch)
-- =====================================================================
CREATE TABLE leads (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id    bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  source        text NOT NULL CHECK (source IN ('website_form','whatsapp','instagram','phone','email',
                                                'agent','walk_in','ota_message','other')),
  property_id   text REFERENCES properties(id),
  check_in      date,
  check_out     date,
  adults        smallint,
  children      smallint,
  occasion_id   bigint REFERENCES occasions(id),
  status        text NOT NULL DEFAULT 'new'
                CHECK (status IN ('new','contacted','quoted','booked','lost')),
  lost_reason   text CHECK (lost_reason IN ('price','dates_unavailable','went_elsewhere',
                                            'no_response','plans_changed','other')),
  quoted_value  numeric(12,2),
  currency      char(3),
  owner_id      bigint REFERENCES staff_users(id),     -- who is following it up
  follow_up_at  timestamptz,
  stay_id       bigint REFERENCES stays(id),           -- set when the lead converts
  created_at    timestamptz NOT NULL DEFAULT now(),
  created_by    bigint REFERENCES staff_users(id),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  updated_by    bigint REFERENCES staff_users(id),
  deleted_at    timestamptz,
  deleted_by    bigint REFERENCES staff_users(id)
);
CREATE INDEX leads_status_idx ON leads (status, follow_up_at) WHERE deleted_at IS NULL;

-- =====================================================================
-- 17. INTERACTIONS – emails, WhatsApps, calls, visits, DMs (empty at launch)
--     staff_id = who spoke to the guest; created_by = who logged it.
-- =====================================================================
CREATE TABLE interactions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id   bigint REFERENCES contacts(id) ON DELETE CASCADE,
  company_id   bigint REFERENCES companies(id) ON DELETE CASCADE,
  kind         text NOT NULL CHECK (kind IN ('email','whatsapp','call','meeting','visit',
                                             'instagram_dm')),
  direction    text CHECK (direction IN ('inbound','outbound')),
  occurred_at  timestamptz NOT NULL DEFAULT now(),
  staff_id     bigint REFERENCES staff_users(id),
  lead_id      bigint REFERENCES leads(id) ON DELETE SET NULL,
  summary      text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  created_by   bigint REFERENCES staff_users(id),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  updated_by   bigint REFERENCES staff_users(id),
  deleted_at   timestamptz,
  deleted_by   bigint REFERENCES staff_users(id),
  CHECK (contact_id IS NOT NULL OR company_id IS NOT NULL)
);
CREATE INDEX interactions_contact_idx ON interactions (contact_id, occurred_at DESC);

-- =====================================================================
-- 18. NOTES – every staff remark, one row per note, newest first in the app.
--     A note is always about a person or a company, and can also point to
--     the stay or lead it concerns. If only a stay or lead is given, the
--     guest is filled in automatically so the note shows on their profile.
-- =====================================================================
CREATE TABLE notes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  body        text NOT NULL,
  contact_id  bigint REFERENCES contacts(id) ON DELETE CASCADE,
  company_id  bigint REFERENCES companies(id) ON DELETE CASCADE,
  stay_id     bigint REFERENCES stays(id) ON DELETE SET NULL,
  lead_id     bigint REFERENCES leads(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  bigint REFERENCES staff_users(id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  bigint REFERENCES staff_users(id),
  deleted_at  timestamptz,
  deleted_by  bigint REFERENCES staff_users(id),
  CHECK (contact_id IS NOT NULL OR company_id IS NOT NULL)
);
CREATE INDEX notes_contact_idx ON notes (contact_id, created_at DESC);
CREATE INDEX notes_company_idx ON notes (company_id, created_at DESC);
CREATE INDEX notes_stay_idx    ON notes (stay_id);
CREATE INDEX notes_lead_idx    ON notes (lead_id);

CREATE OR REPLACE FUNCTION notes_fill_contact() RETURNS trigger AS $$
BEGIN
  IF NEW.contact_id IS NULL AND NEW.stay_id IS NOT NULL THEN
    SELECT contact_id INTO NEW.contact_id FROM stays WHERE id = NEW.stay_id;
  END IF;
  IF NEW.contact_id IS NULL AND NEW.lead_id IS NOT NULL THEN
    SELECT contact_id INTO NEW.contact_id FROM leads WHERE id = NEW.lead_id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER t_notes_fill_contact BEFORE INSERT OR UPDATE ON notes
  FOR EACH ROW EXECUTE FUNCTION notes_fill_contact();

-- =====================================================================
-- 19. DATA ISSUES – review queue for bad emails/phones etc.
-- =====================================================================
CREATE TABLE data_issues (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
