-- =====================================================================
-- 20. CONTACT MERGES – permanent log of duplicates combined by merge_contacts()
--     The duplicate is deleted; this row keeps a full snapshot of it and
--     the ids of every row that moved, so a wrong merge can be rebuilt.
--     created_by = who merged, created_at = when.
-- =====================================================================
CREATE TABLE contact_merges (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kept_contact_id     bigint REFERENCES contacts(id) ON DELETE SET NULL,
  removed_contact_id  bigint NOT NULL,                 -- no FK: that contact no longer exists
  removed_snapshot    jsonb NOT NULL,                  -- the deleted contact + its emails, phones, consents, tags
  moved_rows          jsonb NOT NULL,                  -- {"stays":[ids], "preferences":[ids], …}
  note                text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  created_by          bigint REFERENCES staff_users(id)
);
CREATE INDEX contact_merges_kept_idx ON contact_merges (kept_contact_id);

